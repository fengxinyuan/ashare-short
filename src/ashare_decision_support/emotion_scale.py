"""情绪刻度：炸板率与连板高度的切点，全仓唯一一份。

**放在包根而不是 `strategy/` 下**，理由同 `numeric.py`：它约束的不是某一层的
判断，是**一把尺子**——今天的调用方横跨四层，`adapters/limit_pool.py`（简报里
的措辞）、`sectors/predict.py`（打分斜坡的两个锚点）、`strategy/regime.py`
（情绪周期闸门）、`journal/stats.py`（台账按周期分层）。尺子放进其中任何一层，
另外三层要么够不着（`adapters/` 从不 import `strategy/`），要么得各存一份。

**各存一份的代价不是重复，是同一份简报里两句话打架。** 这不是假设，是删掉这个
模块之前的实际状态——三处的切点分别是 0.25/0.45、0.25/0.55、0.30/0.50：

    炸板率 28%   limit_pool 说「封板有分歧」，regime 说「封板结实」
    炸板率 47%   limit_pool 说「封板意愿弱，情绪退潮」，regime 说「多空分歧」
    最高连板 5   limit_pool 说「有资金愿意接力」，predict 说「接力一般」

而这两句话**一定会同时出现**：`jobs/sources.py` 把涨停池的 `describe()` 倒进
简报 notes，紧接着同一个快照又被交给闸门算周期（涨停池是周期判定的唯一输入）。
读的人看到的是系统对着同一个数字自相矛盾，且没有任何一道闸门会报——三处各自
都有调用方，接线审计看它们全是活的。

`journal/stats.py` 早就写下过这个坑的判据（「闸门按 0.50 切、统计按 0.55 切，
那么退潮期这套规则管不管用的样本，就和真正被闸门拦下的日子对不上」），并且
自己 import 了闸门的值；另外两处只是没跟上。现在四处共用这一份。

**三种用法不同，锚点必须相同。** 措辞是三档硬切、斜坡是两个端点之间线性插值、
闸门是判定阶梯——用法不同不是各定一套的理由，恰恰相反：斜坡的端点和闸门的切点
如果不是同一个数，「打分说偏空」和「闸门说可以做」就会各自成立。

这些数是**先验设定**，来自超短交易里通用的情绪刻度，不是回测出来的。回测框架
建起来之前，它们的作用是让「今天不该做」这件事第一次能被表达出来，而不是精确。
"""

from __future__ import annotations

# 炸板率切点。低于 HEALTHY 封板结实，高于 STRESSED 封板意愿崩塌，高于 FROZEN
# 且没有连板高度就是冰点。
BLOWUP_HEALTHY = 0.30
BLOWUP_STRESSED = 0.50
BLOWUP_FROZEN = 0.60

# 连板高度：有没有资金愿意接力。能出 5 板说明主线在发酵，7 板以上通常已是高潮段。
STREAK_WEAK = 2
STREAK_MOMENTUM = 5
STREAK_CLIMAX = 7
