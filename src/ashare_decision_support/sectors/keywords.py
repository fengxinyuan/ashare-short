def sector_terms(sector: str) -> tuple[str, ...]:
    """Sector name plus its expansion terms, longest first for greedy matching."""
    terms = (sector,) + SECTOR_KEYWORDS.get(sector, ())
    return tuple(sorted(dict.fromkeys(terms), key=len, reverse=True))
